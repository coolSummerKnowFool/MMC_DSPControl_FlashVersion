// 用来存放一些延迟函数等基础功能
#include "basic.h"

/*******************************************************************************
 * 函 数 名         : delay
 * 函数功能         : 延时函数，通过循环占用CPU，达到延时功能
 * 输    入         : 无
 * 输    出         : 无
 *******************************************************************************/
void delay(void)
{
    Uint16 i;
    Uint32 j;
    for (i = 0; i < 32; i++)
        for (j = 0; j < 100000; j++)
            ;
}
